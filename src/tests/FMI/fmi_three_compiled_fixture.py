def _create_fmi_three_scalar_model_description() -> ModelDescription:
    """Create deterministic dual-interface metadata for FMPy's C template.

    FMPy owns the reference FMI 3 ABI surface. VeraGrid supplies fixed identity
    and scalar variables so every generated archive has the same declared
    semantics without copying the upstream implementation into this repository.

    :return: Deterministic scalar Co-Simulation and Model Exchange description.
    """

    # Keep value references aligned with the reference template's generated
    # enumeration so the native getters and setters exercise exact variables.
    time_variable: ModelVariable = ModelVariable(
        name="time",
        valueReference=0,
        type="Float64",
        causality="independent",
        variability="continuous",
        description="Independent time observed by the host-native test FMU.",
    )
    input_variable: ModelVariable = ModelVariable(
        name="control_input",
        valueReference=1,
        type="Float64",
        causality="input",
        variability="continuous",
        start="0.0",
        description="Scalar input used to verify FMI 3 Float64 access.",
    )
    output_variable: ModelVariable = ModelVariable(
        name="observed_output",
        valueReference=2,
        type="Float64",
        causality="output",
        variability="continuous",
        description=(
            "Control input plus completed communication time produced by the "
            "synthetic scalar fixture."
        ),
    )
    structural_gain_variable: ModelVariable = ModelVariable(
        name="structural_gain",
        valueReference=3,
        type="Float64",
        causality="structuralParameter",
        variability="fixed",
        initial="exact",
        start="1.0",
        description="Configuration Mode gain applied to the scalar input.",
    )
    structural_size_variable: ModelVariable = ModelVariable(
        name="structural_size",
        valueReference=4,
        type="UInt64",
        causality="structuralParameter",
        variability="fixed",
        initial="exact",
        start="3",
        description="Scalar UInt64 value used to exercise Configuration Mode.",
    )
    continuous_state_variable: ModelVariable = ModelVariable(
        name="continuous_state",
        valueReference=5,
        type="Float64",
        causality="local",
        variability="continuous",
        initial="exact",
        start="1.0",
        description="Single state owned by the synthetic Model Exchange fixture.",
    )
    state_derivative_variable: ModelVariable = ModelVariable(
        name="state_derivative",
        valueReference=6,
        type="Float64",
        causality="local",
        variability="continuous",
        initial="calculated",
        derivative=continuous_state_variable,
        description="Derivative equal to control_input minus continuous_state.",
    )
    int32_input_variable: ModelVariable = ModelVariable(
        name="integer_input",
        valueReference=7,
        type="Int32",
        causality="input",
        variability="discrete",
        initial="exact",
        start="-2",
        description="Scalar signed input used to verify FMI 3 Int32 access.",
    )
    int32_output_variable: ModelVariable = ModelVariable(
        name="integer_output",
        valueReference=8,
        type="Int32",
        causality="output",
        variability="discrete",
        initial="calculated",
        description="Integer input captured by the latest completed step.",
    )

    # Build the final FMPy model directly. No parallel transfer object survives
    # beyond source generation, and all identity fields remain deterministic.
    fmi_three_description: ModelDescription = ModelDescription()
    fmi_three_description.fmiVersion = "3.0"
    fmi_three_description.modelName = "VeraGridFmiThreeScalarCoSimulationTest"
    fmi_three_description.description = (
        "Repository-generated FMI 3 Co-Simulation host fixture."
    )
    fmi_three_description.generationTool = "VeraGrid FMI test harness with FMPy"
    fmi_three_description.instantiationToken = (
        "b51b3650-6e5f-4f68-9462-6d230981aec0"
    )
    fmi_three_description.coSimulation = CoSimulation(
        modelIdentifier="VeraGridFmiThreeScalarCoSimulationTest",
    )
    # The reference C template exports both FMI 3 instantiation entrypoints.
    # Sharing the identifier lets one compiled artifact prove that worker
    # construction selects the authenticated interface without duplicating a
    # second native build fixture. Its single state exercises the real ME vector
    # lifecycle while all numerical integration remains owned by the caller.
    fmi_three_description.modelExchange = ModelExchange(
        modelIdentifier="VeraGridFmiThreeScalarCoSimulationTest",
    )
    fmi_three_description.modelVariables = list(
        (
            time_variable,
            input_variable,
            output_variable,
            structural_gain_variable,
            structural_size_variable,
            continuous_state_variable,
            state_derivative_variable,
            int32_input_variable,
            int32_output_variable,
        )
    )
    fmi_three_description.outputs = list(
        (
            Unknown(variable=output_variable),
            Unknown(variable=int32_output_variable),
        )
    )
    fmi_three_description.derivatives = list(
        (Unknown(variable=state_derivative_variable),)
    )
    fmi_three_description.initialUnknowns = list(
        (
            Unknown(variable=output_variable),
            Unknown(variable=state_derivative_variable),
            Unknown(variable=int32_output_variable),
        )
    )
    return fmi_three_description


