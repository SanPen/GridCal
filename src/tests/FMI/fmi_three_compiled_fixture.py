def _install_fmi_three_constant_array_dimensions(
    staging_directory: Path,
) -> None:
    """Declare two 3-by-2 arrays in FMPy's generated model description.

    FMPy's C template does not currently render ``Dimension`` elements. The
    fixture adds only those declarative children and the full input start value
    before VeraGrid and FMPy independently parse the resulting FMU.

    :param staging_directory: Extracted source FMU to update declaratively.
    :return: None.
    """

    model_description_path: Path = staging_directory / "modelDescription.xml"
    model_description_tree: ET.ElementTree = ET.parse(model_description_path)
    model_description_root: ET.Element = model_description_tree.getroot()
    model_variables: ET.Element | None = model_description_root.find(
        "ModelVariables"
    )
    if model_variables is not None:
        pass
    else:
        raise AssertionError("Generated FMI 3 array fixture has no ModelVariables")
    array_variable_names: tuple[str, str] = ("array_input", "array_output")
    declared_array_count: int = 0
    variable_element: ET.Element
    for variable_element in model_variables:
        variable_name: str | None = variable_element.attrib.get("name", None)
        if variable_name in array_variable_names:
            first_dimension: ET.Element = ET.SubElement(
                variable_element,
                "Dimension",
            )
            first_dimension.set("start", "3")
            second_dimension: ET.Element = ET.SubElement(
                variable_element,
                "Dimension",
            )
            second_dimension.set("start", "2")
            if variable_name == "array_input":
                variable_element.set("start", "0.0 0.1 1.0 1.1 2.0 2.1")
            else:
                pass
            declared_array_count += 1
        else:
            pass
    if declared_array_count == len(array_variable_names):
        pass
    else:
        raise AssertionError("Generated FMI 3 array variables are incomplete")
    model_exchange: ET.Element | None = model_description_root.find(
        "ModelExchange"
    )
    if model_exchange is not None:
        model_exchange.set("canGetAndSetFMUState", "true")
        model_exchange.set("canSerializeFMUState", "false")
    else:
        raise AssertionError("Generated FMI 3 array fixture has no ModelExchange")
    model_description_tree.write(
        model_description_path,
        encoding="utf-8",
        xml_declaration=True,
    )


