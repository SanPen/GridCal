def _replace_verified_fmi_three_source_block(
    source_text: str,
    start_marker: str,
    end_marker: str,
    expected_sha256: str,
    replacement: str,
    block_name: str,
) -> str:
    """Replace one uniquely delimited FMPy source block after digest validation.

    :param source_text: LF-normalized generated C source.
    :param start_marker: Exact first text owned by the upstream block.
    :param end_marker: Exact first text following the upstream block.
    :param expected_sha256: Approved SHA-256 for FMPy 0.3.26 and 0.3.31.
    :param replacement: VeraGrid-owned deterministic C implementation.
    :param block_name: Block identity used in drift diagnostics.
    :return: Source text containing the verified replacement.
    """

    if source_text.count(start_marker) == 1 and source_text.count(end_marker) == 1:
        pass
    else:
        raise AssertionError(
            f"FMPy {fmpy.__version__} changed the FMI 3 {block_name} source boundaries"
        )
    block_start: int = source_text.index(start_marker)
    block_end: int = source_text.index(end_marker, block_start)
    if block_end > block_start:
        pass
    else:
        raise AssertionError(
            f"FMPy {fmpy.__version__} reordered the FMI 3 {block_name} source block"
        )
    upstream_block: str = source_text[block_start:block_end]
    observed_sha256: str = hashlib.sha256(upstream_block.encode("utf-8")).hexdigest().upper()
    if observed_sha256 == expected_sha256:
        pass
    else:
        raise AssertionError(
            f"FMPy {fmpy.__version__} changed the FMI 3 {block_name} source block "
            f"to SHA-256 {observed_sha256}"
        )
    replaced_source: str = "".join(
        (source_text[:block_start], replacement, source_text[block_end:])
    )
    return replaced_source


