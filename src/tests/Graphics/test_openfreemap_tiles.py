def water_tile() -> bytes:
    """
    Return a reference water polygon covering the left half, with a land hole inside it.

    :return: Small valid vector tile with known top-down coordinates.
    """
    # Fixed reference generated by tilezen/mapbox-vector-tile 2.2.0, not by our decoder.
    return bytes.fromhex(
        '1a300a05776174657212221803221e0900001a802000008040ff1f000f'
        '098008ff371a00800880080000ff070f2880207802')


@pytest.mark.parametrize('style', tuple(MapStyle))
def test_qt_vector_render_preserves_polygon_holes_and_palette(style: MapStyle) -> None:
    """
    Filled water, land and holes must retain their meaning in every palette.

    :param style: Palette under test.
    """
    app: object = ensure_qapplication()
    renderer: VectorTileRenderer = VectorTileRenderer(style)
    image: QImage = QImage.fromData(renderer.render(water_tile(), 0, 0, 0, 0))
    assert app is not None
    assert image.width() == 256 and image.height() == 256
    assert image.pixelColor(16, 16) == renderer.colours.water
    assert image.pixelColor(48, 48) == renderer.colours.land
    assert image.pixelColor(200, 128) == renderer.colours.land


def test_vector_overzoom_crops_parent_data_instead_of_stretching_the_whole_tile() -> None:
    """Adjacent children of one vector tile must display different source regions."""
    app: object = ensure_qapplication()
    renderer: VectorTileRenderer = VectorTileRenderer(MapStyle.Light)
    left: QImage = QImage.fromData(renderer.render(water_tile(), 1, 0, 0, 1))
    right: QImage = QImage.fromData(renderer.render(water_tile(), 1, 0, 1, 1))
    assert app is not None
    assert left.pixelColor(128, 128) == renderer.colours.water
    assert right.pixelColor(128, 128) == renderer.colours.land


def test_cached_gzipped_vectors_render_offline_and_overzoom(tmp_path: Path) -> None:
    """
    A cached TileJSON and compressed parent tile suffice for deep-zoom rendering.

    :param tmp_path: Isolated map cache.
    """
    app: object = ensure_qapplication()
    template: str = 'https://tiles.openfreemap.org/planet/test/{z}/{x}/{y}.pbf'
    (tmp_path / 'tilejson.json').write_text(json.dumps(dict(tiles=list((template,)), maxzoom=0)))
    revision: str = hashlib.sha256(template.encode('utf-8')).hexdigest()[:16]
    tile_path: Path = tmp_path / revision / '0' / '0' / '0.pbf'
    tile_path.parent.mkdir(parents=True)
    tile_path.write_bytes(gzip.compress(water_tile()))
    worker: VectorTileWorker = VectorTileWorker(0, queue.Queue(), str(tmp_path), MapStyle.Dark)
    image: QImage = QImage.fromData(worker.render_tile(2, 0, 3))
    assert app is not None
    assert not image.isNull()
    assert image.pixelColor(128, 128) == VectorTileRenderer(MapStyle.Dark).colours.water


def test_tile_metadata_rejects_unexpected_hosts(tmp_path: Path) -> None:
    """
    Download metadata cannot redirect the tile worker to arbitrary services.

    :param tmp_path: Isolated map cache.
    """
    (tmp_path / 'tilejson.json').write_text(json.dumps(dict(
        tiles=list(('https://example.invalid/{z}/{x}/{y}.pbf',)), maxzoom=14)))
    worker: VectorTileWorker = VectorTileWorker(0, queue.Queue(), str(tmp_path), MapStyle.Light)
    with pytest.raises(ValueError, match='Unexpected OpenFreeMap'):
        worker.load_metadata()


def test_bad_vectors_are_reported_without_becoming_cached_pngs(tmp_path: Path) -> None:
    """
    Malformed protobuf data must follow the worker's error path.

    :param tmp_path: Isolated map cache.
    """
    app: object = ensure_qapplication()
    template: str = 'https://tiles.openfreemap.org/planet/test/{z}/{x}/{y}.pbf'
    (tmp_path / 'tilejson.json').write_text(json.dumps(dict(tiles=list((template,)), maxzoom=0)))
    revision: str = hashlib.sha256(template.encode('utf-8')).hexdigest()[:16]
    tile_path: Path = tmp_path / revision / '0' / '0' / '0.pbf'
    tile_path.parent.mkdir(parents=True)
    tile_path.write_bytes(b'not a vector tile')
    requests: queue.Queue = queue.Queue()
    requests.put((0, 0.0, 0.0))
    requests.put(None)
    worker: VectorTileWorker = VectorTileWorker(0, requests, str(tmp_path), MapStyle.Light)
    results: QSignalSpy = QSignalSpy(worker.tile_available)
    worker.run()
    assert app is not None
    assert results.count() == 1
    assert results.at(0) == [0, 0.0, 0.0, b'', True]
    assert requests.unfinished_tasks == 0


def test_provider_prototypes_copy_and_shutdown_without_network(tmp_path: Path) -> None:
    """
    Only live diagram copies start workers; every copy can stop while idle.

    :param tmp_path: Isolated provider caches.
    """
    app: object = ensure_qapplication()
    sources: list[Tiles] = create_map_tile_sources(str(tmp_path))
    assert app is not None
    assert len(sources) == 4
    assert all(len(source.workers) == 0 for source in sources)
    prototype: OpenFreeMapTiles = sources[2]
    assert prototype.style == MapStyle.Dark
    assert prototype.set_level(10)
    source: OpenFreeMapTiles = prototype.copy()
    try:
        assert source is not prototype
        assert source.level == 10 and source.style == MapStyle.Dark
        assert len(source.workers) == 2
        assert source.request_queue is not prototype.request_queue
        assert source.shutdown()
        assert source.shutdown()
    finally:
        source.shutdown()
        for prototype_source in sources:
            prototype_source.shutdown()


