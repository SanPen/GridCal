def test_palette_switch_preserves_source_zoom_and_exact_map_center(tmp_path: Path) -> None:
    """
    Replacing a provider at the same zoom must still initialize its backing level.

    :param tmp_path: Isolated provider caches.
    """
    app: object = ensure_qapplication()
    sources: list[Tiles] = create_map_tile_sources(str(tmp_path))
    callbacks: MapCallbacks = MapCallbacks()
    widget: MapWidget = MapWidget(None, sources[0], 6, None, callbacks.zoom, callbacks.position)
    old_source: Tiles = widget.tile_src
    try:
        widget.resize(900, 650)
        assert widget.apply_zoom_level(10)
        widget.go_to_position(-16.25, 28.46)
        scale: float = widget.view.schema_zoom
        widget.tile_src = sources[2]
        level: int
        longitude: float
        latitude: float
        level, longitude, latitude = widget.get_level_and_position()
        assert app is not None
        assert level == 10 and widget.tile_src.level == 10
        assert widget.view.schema_zoom == scale
        assert longitude == pytest.approx(-16.25)
        assert latitude == pytest.approx(28.46)
        assert old_source._shutdown_complete
    finally:
        widget.tile_src.shutdown()
        widget.close()
        for source in sources:
            source.shutdown()
